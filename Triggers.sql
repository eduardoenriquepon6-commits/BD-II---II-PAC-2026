CREATE TABLE TBL_LOG_PRODUCTOS (

    PRODUCTOID NUMBER,
    PROVEEDORID NUMBER,
    CATEGORIAID NUMBER,
    DESCRIPCION CHAR(50),
    PRECIOUNIT NUMBER,
    EXISTENCIA NUMBER,
    USUARIO VARCHAR2(50),
    OPERACION VARCHAR2(50),
