CREATE OR REPLACE TRIGGER TG_LOG_PRODUCTOS AFTER INSERT OR UPDATE OR DELETE ON PRODUCTOS
FOR EACH ROW

DECLARE


BEGIN

    IF (INSERTING) THEN

        INSERT INTO TBL_LOG_PRODUCTOS VALUES (

            :NEW.PRODUCTOID,
            NULL,
            NULL,
            NULL,
            NULL,
            NULL,
            USER,
            'INSERT',
            :NEW.PROVEEDORID,
            :NEW.CATEGORIAID,
            :NEW.DESCRIPCION,
            :NEW.PRECIOUNIT,
            :NEW.EXISTENCIA

        );


    ELSIF (UPDATING) THEN
    
        INSERT INTO TBL_LOG_PRODUCTOS VALUES (

            :NEW.PRODUCTOID,
            :OLD.PROVEEDORID,
            :OLD.CATEGORIAID,
            :OLD.DESCRIPCION,
            :OLD.PRECIOUNIT,
            :OLD.EXISTENCIA,
            USER,
            'UPDATE',
            :NEW.PROVEEDORID,
            :NEW.CATEGORIAID,
            :NEW.DESCRIPCION,
            :NEW.PRECIOUNIT,
            :NEW.EXISTENCIA

        );

    ELSIF (DELETING) THEN

        INSERT INTO TBL_LOG_PRODUCTOS VALUES (

            :OLD.PRODUCTOID,
            :OLD.PROVEEDORID,
            :OLD.CATEGORIAID,
            :OLD.DESCRIPCION,
            :OLD.PRECIOUNIT,
            :OLD.EXISTENCIA,
            USER,
            'DELETE',
            NULL,
            NULL,
            NULL,
            NULL,
            NULL

        );

    END IF;

END;

